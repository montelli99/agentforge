import {it,expect,vi} from 'vitest';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {WorkspaceStore} from '../core/store/workspaceStore.js';
import {AgentForgeWebServer} from './webServer.js';

it('requires authenticated execution permission and observes only the saved runtime/run',async()=>{
 const directory=await fs.mkdtemp(path.join(os.tmpdir(),'af-external-route-'));
 const store=new WorkspaceStore(path.join(directory,'workspace.json'));
 for(const [username,permissions] of [['reader',['tasks:read']],['operator',['tasks:read','tasks:execute']]] as const)
  store.createUser({username,displayName:username,role:'viewer',permissions:[...permissions],password:'synthetic test password'});
 const task=store.createTask({title:'Synthetic external task',status:'paused',priority:'medium'});
 store.updateTask(task.id,{externalTurnReceipts:[{requestId:'saved-request',requestDigest:'synthetic-digest',approvalId:'synthetic-approval',connectionId:'saved-connection',sessionKey:'synthetic-session',status:'accepted',runId:'saved-run',createdAt:new Date().toISOString()}]});
 const server=new AgentForgeWebServer(store,0,undefined,undefined,{settingsFilePath:path.join(directory,'settings.json')});
 const inspect=vi.fn(async()=>({runId:'saved-run',status:'timeout'}));
 const submit=vi.fn(async()=>({runId:'submitted-run'}));
 const stop=vi.fn(async()=>({acknowledged:true}));
 server.registerExternalRunConnection({id:'saved-connection',inspectRun:inspect,submitSessionTurn:submit,requestRunStop:stop});
 try{
  await server.start(); const base=server.getBaseUrl();
  const login=async(username:string)=>{const r=await fetch(base+'/api/auth/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({username,password:'synthetic test password'})});expect(r.status).toBe(200);return (await r.json()).token as string;};
  const reader=await login('reader'), operator=await login('operator');
  const connections=(token?:string)=>fetch(base+'/api/runtime-connections',{headers:token?{Authorization:'Bearer '+token}:{}});
  expect((await connections()).status).toBe(401);
  expect((await connections(reader)).status).toBe(403);
  const listed=await connections(operator);expect(listed.status).toBe(200);
  expect(await listed.json()).toEqual({connections:[{id:'saved-connection',canSubmit:true,readiness:'not_checked'}]});
  const reviewTask=store.createTask({title:'Synthetic review task',status:'ready',priority:'medium'});
  const review=(token:string,connectionId='saved-connection')=>fetch(base+'/api/tasks/'+reviewTask.id+'/external-review',{method:'POST',headers:{Authorization:'Bearer '+token,'Content-Type':'application/json'},body:JSON.stringify({connectionId,sessionKey:'selected-session',message:'Exact synthetic delegation'})});
  expect((await review(reader)).status).toBe(403);
  expect((await review(operator,'unregistered')).status).toBe(409);
  expect(store.listApprovals()).toHaveLength(0);
  const prepared=await review(operator);expect(prepared.status).toBe(200);
  const preparedBody=await prepared.json();
  expect(preparedBody.submitted).toBe(false);expect(preparedBody.approval.status).toBe('pending');
  expect(preparedBody.approval.description).toContain('Exact synthetic delegation');
  expect(store.getTask(reviewTask.id)?.externalTurnReceipts).toBeUndefined();
  const dispatch=(message='Exact synthetic delegation')=>fetch(base+'/api/tasks/'+reviewTask.id+'/external-submit',{method:'POST',headers:{Authorization:'Bearer '+operator,'Content-Type':'application/json'},body:JSON.stringify({approvalId:preparedBody.approval.id,connectionId:'saved-connection',sessionKey:'selected-session',message})});
  expect((await dispatch()).status).toBe(409);expect(submit).not.toHaveBeenCalled();
  store.resolveApproval({approvalId:preparedBody.approval.id,status:'approved',approverUserId:'synthetic-reviewer',decisionOrigin:'web'});
  expect((await dispatch('Changed after review')).status).toBe(409);expect(submit).not.toHaveBeenCalled();
  const dispatched=await dispatch();expect(dispatched.status).toBe(200);
  expect(await dispatched.json()).toMatchObject({submitted:true,verified:false,receipt:{runId:'submitted-run',status:'accepted'}});
  expect((await dispatch()).status).toBe(409);expect(submit).toHaveBeenCalledTimes(1);
  const cancel=await fetch(base+'/api/tasks/'+reviewTask.id+'/cancel',{method:'POST',headers:{Authorization:'Bearer '+operator}});
  expect(cancel.status).toBe(200);expect(await cancel.json()).toMatchObject({remoteStopped:false,task:{status:'cancelled'}});
  expect(store.getTask(reviewTask.id)?.externalTurnReceipts?.[0].runId).toBe('submitted-run');
  const stopRequest=(token:string)=>fetch(base+'/api/tasks/'+reviewTask.id+'/external-stop',{method:'POST',headers:{Authorization:'Bearer '+token}});
  expect((await stopRequest(reader)).status).toBe(403);expect(stop).not.toHaveBeenCalled();
  const stopped=await stopRequest(operator);expect(stopped.status).toBe(200);
  expect(await stopped.json()).toMatchObject({stop:{status:'acknowledged'},verified:false});
  expect(stop).toHaveBeenCalledExactlyOnceWith('selected-session','submitted-run');
  expect((await stopRequest(operator)).status).toBe(409);expect(stop).toHaveBeenCalledTimes(1);
  const request=(token?:string,method='POST')=>fetch(base+'/api/tasks/'+task.id+'/external-observation',{method,headers:token?{Authorization:'Bearer '+token}:{}});
  expect((await request()).status).toBe(401);
  expect((await request(reader)).status).toBe(403);
  expect((await request(operator,'GET')).status).toBe(405);
  expect(inspect).not.toHaveBeenCalled();
  const response=await request(operator);
  expect(response.status).toBe(200);expect(response.headers.get('cache-control')).toBe('no-store');
  expect(await response.json()).toMatchObject({runId:'saved-run',observation:{remoteStatus:'timeout'},replayed:false,verified:false});
  expect(inspect).toHaveBeenCalledExactlyOnceWith('saved-run');
  expect(new WorkspaceStore(path.join(directory,'workspace.json')).getTask(task.id)?.status).toBe('paused');
  inspect.mockRejectedValueOnce(Error('private-token-do-not-return'));
  const failed=await request(operator);expect(failed.status).toBe(409);expect(await failed.text()).not.toContain('private-token');
 }finally{await server.stop();await fs.rm(directory,{recursive:true,force:true});}
});
