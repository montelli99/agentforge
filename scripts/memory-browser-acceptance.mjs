import {builtModule} from './built-package-under-test.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {chromium} from 'playwright';
const {WorkspaceStore}=await builtModule('core/store/workspaceStore.js');
const {AgentForgeWebServer}=await builtModule('server/webServer.js');
const executable=process.env.AGENTFORGE_BROWSER_EXECUTABLE;if(!executable||!path.isAbsolute(executable))throw Error('Select an absolute installed Chromium/Chrome executable with AGENTFORGE_BROWSER_EXECUTABLE.');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'agentforge-memory-browser-'));
const store=new WorkspaceStore(path.join(root,'workspace.json'));
process.env.AGENTFORGE_AUTH_STRICT='1';
const workspace=store.createWorkspace({name:'Browser fixture'});
const project=store.createSpace({workspaceId:workspace.id,name:'Import destination',provider:'web'});
const archive={format:'agentforge-memory',schemaVersion:1,namespace:'fixture',exportedAt:'2026-01-02T00:00:00.000Z',records:[{id:'browser-note',namespace:'fixture',projectId:'old-project',category:'do_not_repeat',title:'Synthetic browser lesson',content:'Preserve this synthetic lesson',tags:['fixture'],createdAt:'2026-01-01T00:00:00.000Z'}]};
const file=path.join(root,'collection.json');fs.writeFileSync(file,JSON.stringify(archive));
const server=new AgentForgeWebServer(store,0,undefined,undefined,{settingsFilePath:path.join(root,'settings.json')});let browser;
try{
 await server.start();browser=await chromium.launch({headless:true,executablePath:executable});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(server.getBaseUrl());
 await page.locator('input[name=displayName]').fill('Synthetic owner');await page.locator('input[name=password]').fill('Synthetic browser proof password');await page.getByRole('button',{name:'Secure & continue',exact:true}).click();
 await page.locator('.nav-group-title').filter({hasText:'Management'}).click();await page.getByLabel('Operational memory',{exact:true}).click();
 await page.locator('.memory-collection input').fill('fixture');await page.locator('.memory-collection button').click();
 await page.getByRole('button',{name:'Import collection',exact:true}).click();
 await page.locator('dialog input[type=file]').setInputFiles(file);
 await page.locator('dialog [data-mapping] select').selectOption(project.id);
 await page.getByRole('button',{name:'Review selection',exact:true}).click();
 await page.getByRole('button',{name:'Confirm import',exact:true}).waitFor({state:'visible'});
 await page.waitForFunction(()=>!document.querySelector('dialog [data-commit]').disabled);
 assert.equal(store.listOperationalMemories('fixture').length,0);
 assert.match(await page.locator('dialog [data-preview]').innerText(),/old-project/);
 assert.match(await page.locator('dialog [data-preview]').innerText(),new RegExp(project.id));
 await page.getByRole('button',{name:'Confirm import',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('dialog .conversation-feedback')?.textContent?.includes('1 records saved'));
 assert.equal(store.listOperationalMemories('fixture')[0].projectId,project.id);
 await page.locator('dialog [data-close]').click();
 await page.getByRole('heading',{name:'Synthetic browser lesson',exact:true}).waitFor();
 await page.reload();await page.locator('.memory-collection input').waitFor();assert.equal(await page.locator('.memory-collection input').inputValue(),'fixture');await page.getByRole('heading',{name:'Synthetic browser lesson',exact:true}).waitFor();await page.screenshot({path:path.join(root,'memory-import.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({passed:true,realBrowser:true,syntheticOnly:true,ownerSetup:true,reloadPreserved:true,projectMapping:true,reviewBeforeWrite:true,confirmedImport:true,renderedSavedMemory:true,pageErrors:errors,screenshot:path.join(root,'memory-import.png')}));
}finally{await browser?.close();await server.stop();}
